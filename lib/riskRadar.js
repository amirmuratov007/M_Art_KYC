export function calculateRiskResult(scenario, answers = {}) {
  if (!scenario?.questions?.length) {
    return { score: 0, level: 'low', signals: [], actions: [], answered: 0, total: 0 }
  }

  let weightedScore = 0
  let maximumScore = 0
  const signals = []
  const actions = []
  let answered = 0

  for (const question of scenario.questions) {
    maximumScore += question.weight
    const selected = question.options.find((option) => option.id === answers[question.id])
    if (!selected) continue

    answered += 1
    weightedScore += question.weight * Number(selected.value || 0)

    if (selected.signal && Number(selected.value || 0) >= 0.4) signals.push(selected.signal)
    if (selected.action && Number(selected.value || 0) >= 0.4) actions.push(selected.action)
  }

  const score = maximumScore > 0 ? Math.round((weightedScore / maximumScore) * 100) : 0
  const level = score >= 60 ? 'high' : score >= 30 ? 'medium' : 'low'

  return {
    score,
    level,
    signals: [...new Set(signals)].slice(0, 6),
    actions: [...new Set(actions)].slice(0, 5),
    answered,
    total: scenario.questions.length
  }
}

