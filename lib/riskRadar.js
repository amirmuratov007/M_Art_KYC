export function getDateKey(date = new Date()) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

export function getDailyRiskCase(date = new Date()) {
  const ordinal = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
  return dailyRiskCases[Math.abs(ordinal) % dailyRiskCases.length]
}

export function getRiskRank(xp = 0) {
  if (xp >= 220) return { title: 'Хранитель решения', nextAt: null }
  if (xp >= 110) return { title: 'Риск-менеджер', nextAt: 220 }
  if (xp >= 40) return { title: 'Аналитик', nextAt: 110 }
  return { title: 'Наблюдатель', nextAt: 40 }
}

export function calculateStreak(completedDates = [], now = new Date()) {
  const dates = new Set(completedDates)
  let streak = 0
  const cursor = new Date(now.getFullYear(), now.getMonth(), now.getDate())

  while (dates.has(getDateKey(cursor))) {
    streak += 1
    cursor.setDate(cursor.getDate() - 1)
  }

  if (streak === 0) {
    cursor.setTime(new Date(now.getFullYear(), now.getMonth(), now.getDate() - 1).getTime())
    while (dates.has(getDateKey(cursor))) {
      streak += 1
      cursor.setDate(cursor.getDate() - 1)
    }
  }

  return streak
}

export function createEmptyRiskRadarProgress() {
  return {
    version: 1,
    xp: 0,
    assessments: [],
    daily: {}
  }
}

export function normalizeRiskRadarProgress(value) {
  const fallback = createEmptyRiskRadarProgress()
  if (!value || typeof value !== 'object') return fallback

  return {
    version: 1,
    xp: Math.max(0, Math.min(Number(value.xp) || 0, 100000)),
    assessments: Array.isArray(value.assessments) ? value.assessments.slice(0, 30) : [],
    daily: value.daily && typeof value.daily === 'object' ? value.daily : {}
  }
}
